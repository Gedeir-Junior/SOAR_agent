from pydantic import BaseModel, Field
from typing import List, Optional
from uuid import UUID, uuid4
from datetime import datetime

from .common import PriorityLevel, IncidentStatus


class IncidentAction(BaseModel):
    """
    Action triggered by the SOAR playbook.
    """
    action_type: str = Field(
        ..., description="notify, block, isolate, tag, log"
    )
    target: Optional[str] = Field(
        None, description="user, ip, host, email"
    )
    value: Optional[str] = None
    status: str = Field(default="pending")


class IncidentClassification(BaseModel):
    """
    Final classification after correlation and analysis.
    """
    category: str
    confidence: float = Field(..., ge=0.0, le=1.0)


class SecurityIncident(BaseModel):
    """
    Incident generated by the SOAR Manager.
    """
    incident_id: UUID = Field(default_factory=uuid4)
    created_at: datetime = Field(default_factory=datetime.utcnow)

    status: IncidentStatus = IncidentStatus.open

    priority: PriorityLevel
    risk_score: float = Field(..., ge=0.0)

    related_events: List[UUID]

    classification: IncidentClassification

    actions: List[IncidentAction] = Field(default_factory=list)
